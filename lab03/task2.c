/*
 * Лабораторна робота 3, завдання 2, варіант 1.
 * Знаходимо мінімум кожного стовпця та міняємо перший і останній рядки.
 */

// printf/puts виводять дані; scanf/fgets зчитують введення.
#include <stdio.h>

// Кількість рядків матриці. Допустимі індекси: 0...3.
#define ROWS 4
// Кількість стовпців. Допустимі індекси: 0...4.
#define COLS 5

// Друкуємо матрицю як таблицю. COLS потрібне, щоб компілятор
// знав довжину рядка та міг знайти адресу a[i][j].
static void print_matrix(int a[ROWS][COLS])
{
    // Зовнішній цикл вибирає рядок.
    for (int i = 0; i < ROWS; ++i) {
        // Перебираємо стовпці зліва направо. У вкладеному циклі
        // це послідовний прохід елементів одного рядка.
        for (int j = 0; j < COLS; ++j) {
            // Друкуємо ціле число у полі завширшки не менше 6 символів.
            printf("%6d", a[i][j]);
        }
        // Переводимо друк на наступний рядок.
        putchar('\n');
    }
}

// mins[j] зберігатиме мінімальне значення стовпця j.
static void column_minima(int a[ROWS][COLS], int mins[COLS])
{
    // Перебираємо стовпці зліва направо. У вкладеному циклі
    // це послідовний прохід елементів одного рядка.
    for (int j = 0; j < COLS; ++j) {
        // Початковий мінімум беремо з першого рядка цього стовпця.
        // Якби почали з 0, то для стовпця лише з додатних чисел була б помилка.
        mins[j] = a[0][j];
    }

    // Перший рядок уже враховано. Перевіряємо решту рядків.
    // Спочатку рядок i, усередині стовпець j - це Row-Major Order: 
    // сусідні значення рядка лежать у пам’яті поруч.
    for (int i = 1; i < ROWS; ++i) {
        // Перебираємо стовпці зліва направо. У вкладеному циклі
        // це послідовний прохід елементів одного рядка.
        for (int j = 0; j < COLS; ++j) {
            // Порівнюємо елемент із мінімумом саме його стовпця.
            if (a[i][j] < mins[j]) {
                // Запам’ятовуємо нове найменше значення цього стовпця.
                mins[j] = a[i][j];
            }
        }
    }
}

// Обмінюємо крайні рядки: для кожного стовпця міняємо два елементи.
static void swap_outer_rows(int a[ROWS][COLS])
{
    // Перебираємо стовпці зліва направо. У вкладеному циклі
    // це послідовний прохід елементів одного рядка.
    for (int j = 0; j < COLS; ++j) {
        // Спочатку зберігаємо верхнє значення, щоб не втратити його.
        int temp = a[0][j];
        // На його місце переносимо значення з останнього рядка.
        // Останній індекс дорівнює ROWS - 1, а не ROWS.
        a[0][j] = a[ROWS - 1][j];
        // Збережене верхнє значення переносимо вниз. Обмін завершено.
        a[ROWS - 1][j] = temp;
    }
}

int main(void)
{
    // Фіксована матриця 4 на 5 дозволяє повторити приклад зі звіту.
    int a[ROWS][COLS] = {
        { 12, -3,  7,  0,  9},
        {  4,  8, -6, 11,  2},
        { -5,  1, 10, -4,  6},
        {  3, -9,  5,  8, -2}
    };
    // Окремий одновимірний масив: по одному мінімуму на кожен стовпець.
    int mins[COLS];
    puts("Original matrix:");
    print_matrix(a);
    // Заповнюємо вектор мінімумів. Очікуємо: -5, -9, -6, -4, -2.
    column_minima(a, mins);
    printf("Column minima: ");
    // Перебираємо стовпці зліва направо. У вкладеному циклі
    // це послідовний прохід елементів одного рядка.
    for (int j = 0; j < COLS; ++j) {
        printf("%6d", mins[j]);
    }
    // Переводимо друк на наступний рядок.
    putchar('\n');
    // Змінюємо робочу матрицю. Два середні рядки не чіпаємо.
    // Мінімуми стовпців від перестановки рядків не змінюються.
    swap_outer_rows(a);
    puts("After swapping first and last rows:");
    print_matrix(a);
    // Код 0 означає, що програма завершилася успішно.
    return 0;
}
