// printf/puts виводять дані; scanf/fgets зчитують введення.
#include <stdio.h>

// Максимум 255 байтів тексту; для нуль-термінатора потрібен ще 1 байт.
#define MAX_TEXT 255

// Функція повертає кількість слів. const: текст тут не змінюємо.
static int count_words(const char str[])
{
    // Лічильник знайдених слів.
    int count = 0;
    // Прапорець: 0 - зараз поза словом, 1 - усередині слова.
    int in_word = 0;
    // Скануємо текст посимвольно (точніше, побайтово) до \0.
    // \0 - спеціальний байт кінця C-рядка, а не друкована цифра 0.
    for (int i = 0; str[i] != '\0'; ++i) {
        // Звичайний пробіл завершує слово. Повторні пробіли просто
        // залишають прапорець у стані 0 і не збільшують кількість слів.
        if (str[i] == ' ') {
            in_word = 0;
        // Поточний символ не пробіл, а раніше ми були поза словом.
        // Отже, це початок нового слова: збільшуємо count один раз.
        } else if (!in_word) {
            ++count;
            // Позначаємо, що вже всередині слова. Наступні його літери
            // не збільшуватимуть count, доки не трапиться пробіл.
            in_word = 1;
        }
    }
    // Повертаємо результат із функції в main.
    return count;
}

int main(void)
{
    // Буфер має 256 байтів: до 255 під текст та 1 під \0.
    char str[MAX_TEXT + 1];
    printf("Enter text (up to %d bytes): ", MAX_TEXT);
    // fgets читає рядок зі стандартного введення stdin. sizeof(str)
    // передає повний розмір буфера: функція залишає місце під \0.
    // NULL означає, що не вдалося прочитати рядок.
    if (fgets(str, sizeof(str), stdin) == NULL) {
        fputs("Error: no input line.\n", stderr);
        // Код 1 означає помилку введення або недопустимі параметри.
        return 1;
    }
    // Шукаємо позицію кінця тексту або символу Enter.
    int length = 0;
    // Рухаємося до кінцевого нуля або перенесення рядка \n.
    // && означає, що обидві умови мають бути істинними.
    while (str[length] != '\0' && str[length] != '\n') {
        ++length;
    }
    // Якщо fgets зберегла Enter, замінюємо його нуль-термінатором.
    // Сам Enter не повинен перетворитися на частину останнього слова.
    if (str[length] == '\n') {
        str[length] = '\0';
    // Буфер заповнений. Треба відрізнити рівно 255 байтів тексту
    // від довшого рядка, який fgets прочитала лише частково.
    } else if (length == MAX_TEXT) {
        // Читаємо наступний символ окремо. Змінна int потрібна,
        // щоб умістити і байт символу, і спеціальне значення EOF.
        int ch = getchar();
        // Якщо далі ще є текст, рядок задовгий. Якщо ж Enter або EOF,
        // 255 байтів у буфері є повним допустимим текстом.
        if (ch != '\n' && ch != EOF) {
            // Дочитуємо й відкидаємо залишок надто довгого рядка.
            while ((ch = getchar()) != '\n' && ch != EOF) {

            }
            fputs("Error: text exceeds 255 bytes.\n", stderr);
            // Код 1 означає помилку введення або недопустимі параметри.
            return 1;
        }
    }

    // Додатково прибираємо \r, якщо він залишився від закінчення CRLF.
    // length > 0 потрібне, щоб не звернутися до елемента з індексом -1.
    if (length > 0 && str[length - 1] == '\r') {
        // Спочатку зменшуємо length, потім ставимо новий кінець рядка.
        str[--length] = '\0';
    }
    printf("Text: [%s]\n", str);
    // Передаємо підготовлений текст у count_words і друкуємо результат.
    // Порожній рядок і рядок лише з пробілів дадуть 0 слів.
    printf("Word count: %d\n", count_words(str));
    // Код 0 означає, що програма завершилася успішно.
    return 0;
}
