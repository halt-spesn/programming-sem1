/*
 * Лабораторна робота 3, завдання 1, варіант 1.
 * Шукаємо мінімальний за модулем елемент і суму після першого від’ємного.
 */

// printf/puts виводять дані; scanf/fgets зчитують введення.
#include <stdio.h>
// rand/srand потрібні для випадкових чисел, abs - для модуля int.
#include <stdlib.h>
// Тут потрібна лише strcmp: вона порівнює аргумент запуску з --demo.
#include <string.h>
// time(NULL) дає поточний час для початкового значення генератора.
#include <time.h>

// Масив містить 15 елементів. Їхні індекси - від 0 до 14.
#define SIZE 15

// Функція друкує масив. const забороняє змінювати елементи через a
// в цій функції. static обмежує доступність функції цим файлом.
static void print_array(const int a[SIZE])
{
    // Послідовно перебираємо всі 15 елементів. ++i збільшує індекс на 1.
    for (int i = 0; i < SIZE; ++i) {
        // %d друкує int, а 4 задає мінімальну ширину поля для вирівнювання.
        printf("%4d", a[i]);
    }
    // Після елементів масиву переходимо на новий рядок.
    putchar('\n');
}

// Аналізуємо масив, але його значення не змінюємо.
static void analyze(const int a[SIZE])
{
    // Початковий мінімум беремо з самого масиву, а не довільно з нуля.
    // Зберігаємо саме число зі знаком; порівнювати будемо його модуль.
    int min_value = a[0];
    // Позиція поточного мінімуму; спочатку це нульовий елемент.
    int min_index = 0;
    // -1 означає, що від’ємний елемент ще не знайдено.
    // Це зручно: справжній індекс масиву не може бути від’ємним.
    int first_negative = -1;
    // Сюди накопичуємо суму елементів ПІСЛЯ першого від’ємного.
    int sum = 0;
    // Послідовно перебираємо всі 15 елементів. ++i збільшує індекс на 1.
    for (int i = 0; i < SIZE; ++i) {
        // abs - модуль цілого числа. Якщо модуль менший, оновлюємо
        // значення та індекс. При рівності залишається перший знайдений.
        if (abs(a[i]) < abs(min_value)) {
            min_value = a[i];
            min_index = i;
        }
        // Якщо перший від’ємний уже був на попередній ітерації,
        // поточний елемент розташований після нього: додаємо його до суми.
        if (first_negative >= 0) {
            sum += a[i];
        // Інакше запам’ятовуємо індекс першого від’ємного.
        // Сам цей елемент до суми не додаємо.
        } else if (a[i] < 0) {
            first_negative = i;
        }
    }
    printf("Minimum by absolute value: %d; index: %d\n",
           min_value, min_index);
    // Якщо від’ємних немає, частину «після першого від’ємного»
    // визначити не можна, тому друкуємо окреме повідомлення.
    if (first_negative < 0) {
        puts("No negative element; sum is not calculated.");
    } else {
        printf("First negative index: %d\n", first_negative);
        printf("Sum after first negative: %d\n", sum);
    }
}

// argc - кількість аргументів запуску разом із назвою програми.
// argv - їхні тексти: argv[0] - назва, argv[1] - перший аргумент.
int main(int argc, char *argv[])
{
    // Виділяємо масив фіксованого розміру; malloc тут не потрібен.
    int a[SIZE];
    // && означає «і». Спочатку перевіряємо наявність argv[1].
    // strcmp повертає 0, коли тексти однакові. --demo вмикає
    // фіксований приклад для перевірки та скріншота.
    if (argc == 2 && strcmp(argv[1], "--demo") == 0) {

        // Дані контрольного прикладу: очікувана сума 42,
        // мінімальний модуль має 0 з індексом 5.
        const int demo[SIZE] = {
            12, 7, -8, 4, -3, 0, 15, -2, 9, 6, -1, 5, -4, 11, 2
        };
        // Послідовно перебираємо всі 15 елементів. ++i збільшує індекс на 1.
        for (int i = 0; i < SIZE; ++i) {
            // Копіюємо контрольні числа в робочий масив.
            a[i] = demo[i];
        }
        puts("Mode: fixed demonstration");
    // Без додаткових аргументів виконуємо звичайне випадкове заповнення.
    } else if (argc == 1) {
        // Задаємо початкове значення генератора через поточний час.
        // srand викликаємо один раз перед заповненням, а не на кожному кроці.
        srand((unsigned int)time(NULL));
        // Послідовно перебираємо всі 15 елементів. ++i збільшує індекс на 1.
        for (int i = 0; i < SIZE; ++i) {
            // rand дає псевдовипадкове ціле число. Залишок % 101 дає 0...100;
            // після віднімання 50 отримуємо потрібний діапазон -50...50.
            a[i] = rand() % 101 - 50;
        }
        puts("Mode: random values in [-50; 50]");
    } else {
        fprintf(stderr, "Usage: %s [--demo]\n", argv[0]);
        // Код 1 означає помилку введення або недопустимі параметри.
        return 1;
    }
    printf("Original array: ");
    print_array(a);
    // Викликаємо ту саму функцію аналізу для обох режимів запуску.
    analyze(a);
    // Варіант вимагає обчислення, а не перестановку. Тому масив
    // після аналізу збігається з початковим.
    printf("Array after analysis: ");
    print_array(a);
    // Код 0 означає, що програма завершилася успішно.
    return 0;
}
