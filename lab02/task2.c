/*
 * Лабораторна робота 2, завдання 2, варіант 1.
 * Обчислюємо e^X через суму ряду, знаходячи кожний доданок із попереднього.
 */

// printf/puts виводять дані; scanf/fgets зчитують введення.
#include <stdio.h>
// Математичні функції: exp, fabs та перевірка isfinite.
#include <math.h>

// Не дозволяємо виконати більше 100000 переходів між доданками.
#define MAX_ITER 100000U

int main(void)
{
    // x - аргумент; eps - додатна точність для модуля останнього доданка.
    double x, eps;
    printf("Enter X epsilon: ");
    // Зчитуємо два числа double; & передає адреси змінних.
    // Якщо зчитано менше двох чисел, обчислення не починаємо.
    if (scanf("%lf %lf", &x, &eps) != 2) {
        fprintf(stderr, "Error: enter two numbers.\n");
        // Код 1 означає помилку введення або недопустимі параметри.
        return 1;
    }

    // Ряд e^X математично збігається для всіх дійсних X.
    // Перевіряємо скінченність введених чисел і вимогу eps > 0.
    if (!isfinite(x) || !isfinite(eps) || eps <= 0.0) {
        fprintf(stderr, "Error: finite X and epsilon > 0 required.\n");
        // Код 1 означає помилку введення або недопустимі параметри.
        return 1;
    }
    // Бібліотечна exp обчислює e^X. Беремо її як еталон для порівняння.
    double reference = exp(x);
    // double має обмежений діапазон. Дуже велике e^X може стати
    // нескінченністю, а дуже мале - округлитися до нуля.
    if (!isfinite(reference) || reference == 0.0) {
        fprintf(stderr, "Error: exp(X) is outside double range.\n");
        // Код 1 означає помилку введення або недопустимі параметри.
        return 1;
    }
    // term - поточний доданок a_n. Починаємо з a_0 = 1.
    double term = 1.0;
    // sum - накопичена сума; перший доданок уже врахований.
    double sum = term;
    // n - номер поточного доданка і число рекурентних переходів.
    // У сумі вже є n + 1 доданків, бо відлік починається з нуля.
    unsigned int n = 0;
    // Прапорець помилки: 0 - немає помилки, 1 - обчислення зірвалося.
    int failed = 0;

    // fabs повертає модуль double. Поки поточний доданок не менший
    // за eps, знаходимо наступний. Перший доданок із |term| < eps
    // також додається до суми; потім цикл завершується.
    while (fabs(term) >= eps) {
        // Запобігаємо надто довгим обчисленням: позначаємо помилку
        // й виходимо з while через break.
        if (n >= MAX_ITER) {
            fprintf(stderr, "Warning: iteration limit reached.\n");
            failed = 1;
            break;
        }
        // Переходимо від номера n - 1 до номера n.
        ++n;
        // Рекурентна формула: a_n = a_(n-1) * X / n.
        // *= означає «помножити й записати назад у term».
        // (double)n явно перетворює n на дійсне число.
        // Степінь X^n та факторіал n! окремо не обчислюємо.
        term *= x / (double)n;
        // Обчислюємо нову суму окремо, щоб перевірити її до збереження.
        double next_sum = sum + term;
        // Якщо доданок або сума переповнили double, результат не приймаємо.
        if (!isfinite(term) || !isfinite(next_sum)) {
            fprintf(stderr, "Error: intermediate overflow.\n");
            failed = 1;
            break;
        }
        // Зберігаємо перевірену нову суму.
        sum = next_sum;
    }
    // Якщо всередині циклу була помилка, не друкуємо суму як успішний
    // результат. Код 2 позначає помилку саме під час обчислень.
    if (failed) {
        return 2;
    }
    // Абсолютна похибка - модуль різниці між сумою ряду та exp(X).
    double abs_error = fabs(sum - reference);
    // Відносна похибка - абсолютна похибка, поділена на модуль еталона.
    // Це частка, не відсотки. Для відсотків треба помножити на 100.
    double rel_error = abs_error / fabs(reference);
    // %.12g друкує до 12 значущих цифр, %u нижче - беззнаковий int.
    printf("Series sum     = %.12g\n", sum);
    printf("exp(X)         = %.12g\n", reference);
    printf("Absolute error = %.12g\n", abs_error);
    printf("Relative error = %.12g\n", rel_error);
    printf("Iterations     = %u\n", n);
    printf("Last term      = %.12g\n", term);
    // Для великих від’ємних X додатні та від’ємні члени можуть взаємно
    // скорочуватися з втратою точності. Виводимо попередження.
    if (x < -20.0) {
        printf("Warning: cancellation may reduce accuracy.\n");
    }
    // Код 0 означає, що програма завершилася успішно.
    return 0;
}
