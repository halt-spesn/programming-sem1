/*
 * Лабораторна робота 2, завдання 1, варіант 1.
 * Для кожного X від start до end обчислюємо Y за однією з трьох формул.
 */

// printf/puts виводять дані; scanf/fgets зчитують введення.
#include <stdio.h>
// Математичні функції: exp, fabs та перевірка isfinite.
#include <math.h>

// Обмеження кількості рядків таблиці. U означає беззнакову константу.
#define MAX_ROWS 100000U

// Окрема функція обчислює Y для одного X і друкує рядок таблиці.
// void: функція нічого не повертає. static: доступна в цьому файлі.
static void print_row(double x)
{
    // Тут зберігатиметься значення функції для поточного X.
    double y;
    // Перша гілка: якщо X не додатний, Y = -X.
    if (x <= 0.0) {
        y = -x;
    // Сюди потрапляє тільки X > 0. Якщо X <= 2, то Y = X у квадраті.
    } else if (x <= 2.0) {
        y = x * x;
    } else {
        // Для всіх X > 2 значення функції постійне: 4.
        y = 4.0;
    }
    // isfinite перевіряє, чи число скінченне. ! означає заперечення.
    // Якщо отримано нескінченність або NaN, друкуємо позначку помилки.
    if (!isfinite(y)) {
        printf("%12.6g | [Не визначено]\n", x);
    } else {
        // 12 - ширина поля. .6f - шість цифр після крапки; .6g - до шести
        // значущих цифр. Символ \n переводить виведення на новий рядок.
        printf("%12.6g | %12.6f\n", x, y);
    }
}

int main(void)
{
    // start/end - ліва/права межа; dx - додатний крок табулювання.
    double start, end, dx;
    printf("Enter X_start X_end dX: ");
    // %lf зчитує double. & передає адресу змінної, куди записати число.
    // scanf має успішно зчитати рівно три значення.
    if (scanf("%lf %lf %lf", &start, &end, &dx) != 3) {
        fprintf(stderr, "Error: enter three numbers.\n");
        // Код 1 означає помилку введення або недопустимі параметри.
        return 1;
    }
    // || означає «або»: достатньо однієї неправильної умови.
    // Відхиляємо NaN/нескінченності, зворотні або рівні межі та крок <= 0.
    if (!isfinite(start) || !isfinite(end) ||
        !isfinite(dx) || start >= end || dx <= 0.0) {
        fprintf(stderr, "Error: finite values, start < end, dX > 0.\n");
        // Код 1 означає помилку введення або недопустимі параметри.
        return 1;
    }
    // Приблизно оцінюємо число кроків до запуску циклу.
    // long double використовуємо для обчислення цієї оцінки.
    long double steps = ((long double)end - start) / dx;
    // Залишаємо запас для початкової точки та окремого виведення кінця.
    if (steps > MAX_ROWS - 2U) {
        fprintf(stderr, "Error: too many rows; increase dX.\n");
        // Код 1 означає помилку введення або недопустимі параметри.
        return 1;
    }
    printf("%12s | %12s\n", "X", "Y(X)");
    // Лічильник уже надрукованих рядків, початково 0.
    unsigned int rows = 0;
    // Починаємо з лівої межі. Крок виконуємо в кінці тіла циклу вручну,
    // тому третя частина for порожня.
    for (double x = start; x <= end; ) {
        // ++rows спочатку збільшує лічильник. Це додатковий захист від
        // занадто довгого циклу, навіть після попередньої оцінки steps.
        if (++rows > MAX_ROWS) {
            fprintf(stderr, "Error: row limit reached.\n");
            // Код 1 означає помилку введення або недопустимі параметри.
            return 1;
        }
        // Обчислюємо та друкуємо поточну точку.
        print_row(x);
        // Якщо праву межу вже надруковано, більше точок не потрібно.
        // break одразу завершує найближчий цикл.
        if (x == end) {
            break;
        }
        // Обчислюємо наступне значення аргументу.
        double next = x + dx;
        // Дуже малий крок може загубитися при округленні double.
        // Якщо X не зростає, зупиняємося, щоб не зациклитися.
        if (next <= x) {
            fprintf(stderr, "Error: dX too small for double.\n");
            // Код 1 означає помилку введення або недопустимі параметри.
            return 1;
        }
        // Якщо наступна точка вже за межами відрізка, друкуємо сам end.
        // Так права межа потрапляє в таблицю навіть при некратному кроці.
        if (!isfinite(next) || next > end) {
            print_row(end);
            break;
        }
        // Переходимо до наступної точки й повторюємо перевірку for.
        x = next;
    }
    // Код 0 означає, що програма завершилася успішно.
    return 0;
}
